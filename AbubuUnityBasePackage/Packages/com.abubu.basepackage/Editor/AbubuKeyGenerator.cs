using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using Abubu.Audio;
using Abubu.Effects;
using Abubu.Localization;
using UnityEditor;
using UnityEngine;

namespace Abubu.Editor
{
    /// <summary>
    /// Tools > Abubu > Generate Keys
    /// SoundLibrary / EffectLibrary / AbubuLocalizationTable に登録されたキーと Build Profiles のシーン名から、文字列リテラルの代わりに使える定数クラスを生成する。
    /// <code>
    /// Sound.PlaySe(SoundKeys.Se.Jump);        // "jump" と書くより、タイポがコンパイルエラーになる
    /// Fx.Play(EffectKeys.Explosion, pos);
    /// Scenes.Load(SceneKeys.Game);
    /// Loc.Get(LocKeys.MenuStart);           // "menu.start"
    /// </code>
    /// </summary>
    /// <remarks>
    /// 出力先・名前空間・asmdef の生成は Edit > Project Settings > Abubu で変更できる (既定は Assets/Abubu/Generated/AbubuKeys.cs)。
    /// 内容が変わらなければ書き込まないので、何度実行しても安全。
    /// ライブラリやシーン一覧を編集したら再実行すること (自動では更新されない)。
    /// </remarks>
    public static class AbubuKeyGenerator
    {
        [MenuItem("Tools/Abubu/Generate Keys", priority = 20)]
        public static void Generate()
        {
            var settings = AbubuEditorSettings.instance;
            var outputPath = string.IsNullOrWhiteSpace(settings.KeysOutputPath) ? "Assets/Abubu/Generated/AbubuKeys.cs" : settings.KeysOutputPath.Trim();
            var outputFolder = Path.GetDirectoryName(outputPath)!.Replace('\\', '/');
            var source = Build(CollectSoundKeys(), CollectEffectKeys(), CollectSceneNames(), CollectLocalizationKeys(), settings.KeysNamespace);

            Directory.CreateDirectory(outputFolder);
            var changed = WriteIfChanged(outputPath, source);
            if (settings.KeysGenerateAsmdef && !string.IsNullOrWhiteSpace(settings.KeysAsmdefName))
            {
                var asmdefPath = $"{outputFolder}/{settings.KeysAsmdefName.Trim()}.asmdef";
                changed |= WriteIfChanged(asmdefPath, BuildAsmdef(settings.KeysAsmdefName.Trim(), settings.KeysNamespace));
            }

            Debug.Log(changed ? $"[Abubu] キー定数を生成しました: {outputPath}" : $"[Abubu] キー定数は最新です: {outputPath}");
        }

        private static bool WriteIfChanged(string path, string text)
        {
            if (File.Exists(path) && File.ReadAllText(path) == text) return false;
            File.WriteAllText(path, text, new UTF8Encoding(false));
            AssetDatabase.ImportAsset(path);
            return true;
        }

        /// <summary>定数だけの asmdef (他のアセンブリを参照しない)</summary>
        internal static string BuildAsmdef(string name, string rootNamespace) =>
            "{\n" +
            $"    \"name\": \"{Escape(name)}\",\n" +
            $"    \"rootNamespace\": \"{Escape(rootNamespace ?? string.Empty)}\",\n" +
            "    \"references\": [],\n" +
            "    \"autoReferenced\": true,\n" +
            "    \"noEngineReferences\": true\n" +
            "}\n";

        /// <summary>カテゴリ → キー一覧。プロジェクト内の全 SoundLibrary (includes 先を含む) を集める</summary>
        private static Dictionary<SoundCategory, List<string>> CollectSoundKeys()
        {
            var libraries = FindAssets<SoundLibrary>();
            var result = new Dictionary<SoundCategory, List<string>>();
            foreach (SoundCategory category in Enum.GetValues(typeof(SoundCategory)))
            {
                result[category] = libraries.SelectMany(l => l.GetKeys(category)).Distinct().OrderBy(k => k, StringComparer.Ordinal).ToList();
            }
            return result;
        }

        private static List<string> CollectEffectKeys() =>
            FindAssets<EffectLibrary>().SelectMany(l => l.Keys).Distinct().OrderBy(k => k, StringComparer.Ordinal).ToList();

        private static List<string> CollectLocalizationKeys() =>
            FindAssets<AbubuLocalizationTable>().SelectMany(t => t.GetAllKeys()).Distinct().OrderBy(k => k, StringComparer.Ordinal).ToList();

        /// <summary>Build Profiles (Build Settings) で有効になっているシーンの名前</summary>
        private static List<string> CollectSceneNames() =>
            EditorBuildSettings.scenes.Where(s => s.enabled && !string.IsNullOrEmpty(s.path))
                .Select(s => Path.GetFileNameWithoutExtension(s.path))
                .Distinct().OrderBy(n => n, StringComparer.Ordinal).ToList();

        private static List<T> FindAssets<T>() where T : UnityEngine.Object =>
            AssetDatabase.FindAssets($"t:{typeof(T).Name}", AbubuEditorSettings.instance.SearchFolders)
                .Select(guid => AssetDatabase.LoadAssetAtPath<T>(AssetDatabase.GUIDToAssetPath(guid)))
                .Where(a => a != null)
                .ToList();

        /// <summary>生成するソースコードを組み立てる (テストしやすいよう副作用なし)</summary>
        internal static string Build(IReadOnlyDictionary<SoundCategory, List<string>> sound, IReadOnlyList<string> effects,
            IReadOnlyList<string> scenes = null, IReadOnlyList<string> localization = null, string ns = "Abubu")
        {
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated>");
            sb.AppendLine("// Tools > Abubu > Generate Keys で生成されました。手で編集しないでください。");
            sb.AppendLine("// </auto-generated>");
            sb.AppendLine($"namespace {(string.IsNullOrWhiteSpace(ns) ? "Abubu" : ns.Trim())}");
            sb.AppendLine("{");
            sb.AppendLine("    /// <summary>SoundLibrary のキー定数</summary>");
            sb.AppendLine("    public static class SoundKeys");
            sb.AppendLine("    {");
            foreach (var category in new[] { SoundCategory.Bgm, SoundCategory.Se, SoundCategory.Ambient, SoundCategory.Voice })
            {
                sb.AppendLine($"        public static class {category}");
                sb.AppendLine("        {");
                AppendConstants(sb, sound.TryGetValue(category, out var keys) ? keys : new List<string>(), "            ", category.ToString());
                sb.AppendLine("        }");
            }
            sb.AppendLine("    }");
            sb.AppendLine();
            sb.AppendLine("    /// <summary>EffectLibrary のキー定数</summary>");
            sb.AppendLine("    public static class EffectKeys");
            sb.AppendLine("    {");
            AppendConstants(sb, effects, "        ", "EffectKeys");
            sb.AppendLine("    }");
            sb.AppendLine();
            sb.AppendLine("    /// <summary>Build Profiles に登録されたシーン名の定数</summary>");
            sb.AppendLine("    public static class SceneKeys");
            sb.AppendLine("    {");
            AppendConstants(sb, scenes ?? Array.Empty<string>(), "        ", "SceneKeys");
            sb.AppendLine("    }");
            sb.AppendLine();
            sb.AppendLine("    /// <summary>LocalizationTable のキー定数</summary>");
            sb.AppendLine("    public static class LocKeys");
            sb.AppendLine("    {");
            AppendConstants(sb, localization ?? Array.Empty<string>(), "        ", "LocKeys");
            sb.AppendLine("    }");
            sb.AppendLine("}");
            return sb.ToString();
        }

        private static void AppendConstants(StringBuilder sb, IEnumerable<string> keys, string indent, string ownerName)
        {
            foreach (var (name, key) in AssignIdentifiers(keys, ownerName))
            {
                sb.AppendLine($"{indent}public const string {name} = \"{Escape(key)}\";");
            }
        }

        /// <summary>
        /// キーに定数名を割り当てる。別のキーが同じ識別子になる場合は、文字列順で最初のキーだけがそのままの名前になり、
        /// 残りはキーから計算した固定の接尾辞 (_1a2b) が付く。関係ないキーを追加しても、既存の定数名は変わらない
        /// </summary>
        internal static List<(string Name, string Key)> AssignIdentifiers(IEnumerable<string> keys, string ownerName)
        {
            var result = new List<(string, string)>();
            var used = new HashSet<string>();
            foreach (var group in keys.Distinct().GroupBy(k => Sanitize(ToIdentifier(k), ownerName)).OrderBy(g => g.Key, StringComparer.Ordinal))
            {
                var ordered = group.OrderBy(k => k, StringComparer.Ordinal).ToList();
                for (var i = 0; i < ordered.Count; i++)
                {
                    var name = i == 0 ? group.Key : $"{group.Key}_{StableHash(ordered[i]):x4}";
                    // 接尾辞まで重なることはまず無いが、念のため確実に一意にする
                    var unique = name;
                    for (var n = 2; !used.Add(unique); n++) unique = name + "_" + n;
                    result.Add((unique, ordered[i]));
                }
            }
            return result;
        }

        // メンバー名は囲んでいる型と同じにできない (例: SoundKeys.Se の中の "se")
        private static string Sanitize(string name, string ownerName) => name == ownerName ? name + "_" : name;

        /// <summary>実行環境に依存しない 16 bit のハッシュ (FNV-1a)。string.GetHashCode は実行ごとに変わり得るので使わない</summary>
        private static int StableHash(string text)
        {
            unchecked
            {
                var hash = 2166136261u;
                foreach (var c in text)
                {
                    hash ^= c;
                    hash *= 16777619u;
                }
                return (int)((hash ^ (hash >> 16)) & 0xFFFF);
            }
        }

        /// <summary>"title_bgm" → "TitleBgm"、"1up" → "_1up" (先頭は必ず大文字になるため予約語とは衝突しない)</summary>
        internal static string ToIdentifier(string key)
        {
            var sb = new StringBuilder();
            var upperNext = true;
            foreach (var c in key)
            {
                if (!char.IsLetterOrDigit(c))
                {
                    upperNext = true;
                    continue;
                }
                sb.Append(upperNext ? char.ToUpperInvariant(c) : c);
                upperNext = false;
            }

            if (sb.Length == 0) return "_";
            if (char.IsDigit(sb[0])) sb.Insert(0, '_');

            return sb.ToString();
        }

        /// <summary>
        /// C# の文字列リテラルとして埋め込めるようにする。
        /// 改行・制御文字・行区切り (U+2028 など) が残ると、生成したファイルのコンパイルエラーでプロジェクト全体が止まるため \uXXXX にする
        /// </summary>
        internal static string Escape(string key)
        {
            var sb = new StringBuilder(key.Length);
            foreach (var c in key)
            {
                if (c == '\\') sb.Append("\\\\");
                else if (c == '"') sb.Append("\\\"");
                else if (char.IsControl(c) || c == '\u2028' || c == '\u2029') sb.Append($"\\u{(int)c:X4}");
                else sb.Append(c);
            }
            return sb.ToString();
        }
    }
}
